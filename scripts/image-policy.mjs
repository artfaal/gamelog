// Политика качества кадров — один канон: проверку гоняет scripts/image.mjs.
// Кадр показывается в ленте (пара в ряд) и в лайтбоксе на весь экран, так что
// порог веса — про страницу целиком, а не про одну картинку.
export const LIMITS = {
  // разметка ленты объявляет кадр как 1920×1080 (build.mjs), лайтбокс жмёт его
  // по высоте экрана — выше исходник не показывается нигде, только весит
  width: 1920,
  height: 1080,
  // вес меряется плотностью, а не жёстким потолком: в media лежат и полные 1080p,
  // и узкие кропы (739×415) — мерить их одним числом КБ значит равнять кроп с
  // полным кадром.
  // 175 КБ/Мпикс = ~360 КБ на полный 1080p. Порог поставлен так, чтобы кадр,
  // снятый и сохранённый с разумным качеством, проходил без пережатия: боевой
  // dlc1-boss даёт 167 и проходит, а 150 отсекал бы и его — то есть требовал бы
  // ухудшать картинку без выигрыша. У записи бывает 4–6 кадров, до ~2 МБ, и то
  // лениво: в ленте они под loading=lazy
  kbPerMegapixel: 175,
  // -q:v для mjpeg в ffmpeg (шкала 2…31, меньше — лучше). 4 выбрано замером:
  // SSIM 0.98 к исходнику, в политику влезает с запасом; 3 уже вылезает (345 КБ)
  quality: 4,
  // png в media — логотипы и постеры с прозрачностью, а не фото: формат без
  // потерь, плоская графика жмётся в разы плотнее, и КБ/Мпикс для неё врёт
  // (логотип 800×300 — это 0,24 Мпикс, любой честный вес выглядит нарушением).
  // Поэтому у png один порог — абсолютный: логотип тяжелее 150 КБ либо
  // непомерно большой, либо внутри него фотография, которой место в jpg
  pngKbTotal: 150,
};

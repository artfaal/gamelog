// Русские числа дневника: разряды, склонение и десятичная запятая.
// Отдельный модуль, потому что правило склонения при дробях неочевидно и проверяется
// тестами (scripts/test.mjs) — в живом контенте дробных часов сейчас нет.

// Разряды режем узким неразрывным пробелом: часы растут ~500 в год, «1472 ч» читается
// хуже. Десятичная точка — в запятую: в дневнике всё русским по-русски, «8,5 из 10».
export const ruNum = n => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, " ").replace(".", ",");

export const plural = (n, one, few, many) => {
  // дробное число по-русски идёт с родительным единственного: «41,5 часа», а не «часов».
  // Steam отдаёт наигранное дробным, и половинный час в записи — обычное дело
  if (!Number.isInteger(Number(n))) return `${ruNum(n)} ${few}`;
  const m10 = n % 10, m100 = n % 100;
  return `${ruNum(n)} ${(m100 >= 11 && m100 <= 14) ? many : m10 === 1 ? one : (m10 >= 2 && m10 <= 4) ? few : many}`;
};

export const ruHours = n => plural(n, "час", "часа", "часов");
export const ruGames = n => plural(n, "игра", "игры", "игр");

// оценка бывает половинной: 8.5 → 8,5. Запятую не двигаем — цифры Cormorant
// свисают ниже строки по-разному (7 и 9 да, 8 и 6 нет), и любой сдвиг ровен
// для одной пары и кривой для другой
export const ruScore = n => String(n).replace(".", ",");

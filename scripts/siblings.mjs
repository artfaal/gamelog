// Связки между заходами одной игры: кто из них первый и как подписать ссылку на соседа.
// Отдельный модуль, потому что это единственная часть сборки с нетривиальным правилом,
// а живого контента с повторными заходами сейчас нет — проверяется в scripts/test.mjs.

// Ключ игры: appid, ручной game или слаг. String() обязателен — YAML отдаёт
// `steam: 668580` числом, а `steam: "668580"` строкой, и кэш у них общий.
export const gameKey = e => String(e.fm.steam ?? e.fm.game ?? e.slug);

// Первый заход игры: дата решает, слаг разрешает ничью. Без второго ключа две записи
// одного дня считали первой каждая себя, и одна ссылка получала в разных карточках
// разные подписи. «Сейчас играю» в счёт не идёт — у него нет даты.
export const firstRun = runs => [...runs]
  .filter(o => !o.playing)
  .sort((a, b) => String(a.fm.finished).localeCompare(String(b.fm.finished))
    || a.slug.localeCompare(b.slug))[0] ?? null;

// Подпись ссылки на соседний заход: его исход и место во времени относительно текущего.
// «Отложил» — такой же исход, как дроп и прохождение (README, «Сейчас играю и „пока
// не знаю“»), и без своей ветки отложенный заход подписывался «прошёл». «Первый заход»
// говорится только про действительно первый: при трёх заходах любой ранний сосед иначе
// назывался бы первым.
export const siblingLabel = (сосед, текущая, первый) => {
  const year = String(сосед.fm.finished).slice(0, 4);
  const позже = сосед.fm.finished > текущая.fm.finished;
  if (сосед.playing) return "сейчас играю";
  if (сосед.dropped) return позже ? `потом дропнул в ${year}` : `${первый ? "первый заход — дроп" : "дроп"} в ${year}`;
  if (сосед.paused) return позже ? `вернулся и отложил в ${year}` : `отложил в ${year}`;
  return позже ? `вернулся и прошёл в ${year}` : `прошёл в ${year}`;
};
